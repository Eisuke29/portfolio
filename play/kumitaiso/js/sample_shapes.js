// 座標は 256×144 で書き、細かい形（MASK_W×MASK_H）に拡大して塗る
function capsMask(parts) {
  const m = new Float32Array(MASK_W * MASK_H), k = MASK_W / SEG_W;
  parts.forEach(function (q0) {
    const q = [[q0[0][0] * k, q0[0][1] * k], [q0[1][0] * k, q0[1][1] * k], q0[2] * k];
    const a = q[0], b = q[1], r = q[2] / 2;
    for (let y = 0; y < MASK_H; y++) for (let x = 0; x < MASK_W; x++) {
      const vx = b[0] - a[0], vy = b[1] - a[1], L2 = vx * vx + vy * vy || 1e-9;
      let u = ((x + 0.5 - a[0]) * vx + (y + 0.5 - a[1]) * vy) / L2; u = Math.max(0, Math.min(1, u));
      const dx = x + 0.5 - a[0] - u * vx, dy = y + 0.5 - a[1] - u * vy;
      if (dx * dx + dy * dy <= r * r) m[y * MASK_W + x] = 1;
    }
  });
  return m;
}
// 体の共通部分：頭・胴・脚（legs：'together'＝少し開く／'apart'＝大きく開く）
function body(legs) {
  const L = legs === 'apart' ? [[121, 80], [90, 141], [135, 80], [166, 141]] : [[122, 80], [113, 141], [134, 80], [143, 141]];
  return [
    [[128, 17], [128, 17], 22],                 // 頭
    [[128, 40], [128, 76], 30],                 // 胴
    [L[0], L[1], 15], [L[2], L[3], 15]           // 脚
  ];
}
